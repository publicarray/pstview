/// Standalone HTML report for one message's headers.
pub fn html(a: Allocator, an: hd.Analysis, source: []const u8, fmt_time: TimeFmt) ![]u8 {
    var o: List = .empty;
    var tb: [96]u8 = undefined;
    var tb2: [64]u8 = undefined;
    try o.appendSlice(a, "<!doctype html><html><head><meta charset=\"utf-8\"><meta http-equiv=\"Content-Security-Policy\" content=\"default-src 'none'; style-src 'unsafe-inline'\"><title>Header analysis - ");
    try esc(a, &o, if (an.subject.len > 0) an.subject else "message");
    try o.print(a, "</title><style>{s}</style></head><body><h1>Message header analysis</h1><p class=\"sub\">", .{css});
    try esc(a, &o, if (an.subject.len > 0) an.subject else "(no subject)");
    if (source.len > 0) {
        try o.appendSlice(a, " &middot; ");
        try esc(a, &o, source);
    }
    try o.appendSlice(a, " &middot; generated by pstview offline (no DNS, reputation or geo-IP lookups were made)</p>");

    // ---- verdict
    const vclass = if (!an.has_headers) "muted" else if (an.risk == .none) "ok" else sevClass(an.risk);
    try o.print(a, "<div class=\"verdict {s}\"><span class=\"{s}\">", .{ vclass, vclass });
    try o.appendSlice(a, if (!an.has_headers) "No internet headers" else if (an.risk == .none) "No significant issues found" else switch (an.risk) {
        .high => "High risk indicators",
        .medium => "Medium risk indicators",
        else => "Low risk indicators",
    });
    try o.appendSlice(a, "</span>");
    if (an.findings.len > 0) {
        try o.appendSlice(a, "<ul>");
        for (an.findings) |f| {
            try o.print(a, "<li><span class=\"{s}\">[{s}]</span> ", .{ sevClass(f.sev), f.sev.label() });
            try esc(a, &o, f.text);
            try o.appendSlice(a, "</li>");
        }
        try o.appendSlice(a, "</ul>");
    }
    try o.appendSlice(a, "</div>");
    if (!an.has_headers) {
        try o.appendSlice(a, "<p>This item has no stored internet headers (internal message, sent item or draft).</p></body></html>");
        return o.toOwnedSlice(a);
    }

    // ---- summary
    try o.appendSlice(a, "<h2>Summary</h2><table>");
    const Row = struct { k: []const u8, v: []const u8 };
    var from_disp: List = .empty;
    if (an.from_name.len > 0) try from_disp.print(a, "{s} <{s}>", .{ an.from_name, an.from_addr }) else try from_disp.appendSlice(a, an.from_addr);
    var date_disp: List = .empty;
    if (an.date) |d| try date_disp.print(a, "{s}  ({s})", .{ fmt_time(&tb, d), utc(&tb2, d) });
    var transit: List = .empty;
    if (an.transit) |t| {
        var db: [32]u8 = undefined;
        try transit.print(a, "{s} over {d} hop(s)", .{ hd.fmtDuration(&db, t), an.hops.len });
    }
    const rows = [_]Row{
        .{ .k = "Subject", .v = an.subject },          .{ .k = "From", .v = from_disp.items },
        .{ .k = "Sender", .v = an.sender },            .{ .k = "Reply-To", .v = an.reply_to },
        .{ .k = "Return-Path", .v = an.return_path },  .{ .k = "To", .v = an.to },
        .{ .k = "Cc", .v = an.cc },                    .{ .k = "Delivered-To", .v = an.delivered_to },
        .{ .k = "Date", .v = date_disp.items },        .{ .k = "Message-ID", .v = an.message_id },
        .{ .k = "In-Reply-To", .v = an.in_reply_to },  .{ .k = "Mailer", .v = an.mailer },
        .{ .k = "Delivery time", .v = transit.items }, .{ .k = "Sender device / IP", .v = if (an.origin_ip.len > 0) (std.fmt.allocPrint(a, "{s} [{s}]", .{ hd.orDash(an.origin_device), an.origin_ip }) catch "") else "" },
    };
    for (rows) |r| {
        if (r.v.len == 0) continue;
        try o.print(a, "<tr><td class=\"k\">{s}</td><td>", .{r.k});
        try esc(a, &o, r.v);
        try o.appendSlice(a, "</td></tr>");
    }
    try o.appendSlice(a, "</table>");

    // ---- authentication
    try o.appendSlice(a, "<h2>Authentication</h2><div class=\"cards\">");
    try card(a, &o, "SPF", an.spf, an.spf_domain, an.spf_alignment);
    try card(a, &o, "DKIM", an.dkim, an.dkim_domain, an.dkim_alignment);
    try o.print(a, "<div class=\"card\"><b>DMARC</b><span class=\"{s}\">", .{resultClass(an.dmarc)});
    try esc(a, &o, hd.orDash(an.dmarc));
    try o.appendSlice(a, "</span><div class=\"note\">reported by receiver; computed: ");
    try esc(a, &o, an.dmarcComputed());
    try o.appendSlice(a, "</div></div>");
    if (an.compauth.len > 0) {
        try o.print(a, "<div class=\"card\"><b>Microsoft compauth</b><span class=\"{s}\">", .{resultClass(an.compauth)});
        try esc(a, &o, an.compauth);
        try o.appendSlice(a, "</span><div class=\"note\">");
        try esc(a, &o, if (an.compauth_reason.len > 0) (std.fmt.allocPrint(a, "reason {s}", .{an.compauth_reason}) catch "") else "");
        try o.appendSlice(a, "</div></div>");
    }
    try o.appendSlice(a, "</div><p class=\"note\">The cards use the first-arrival result (when the message entered the receiving organisation); alignment is relaxed (same organisational domain as From: ");
    try esc(a, &o, hd.orDash(an.from_domain));
    try o.appendSlice(a, ").</p>");
    if (an.auth.len > 0) {
        try o.appendSlice(a, "<h3>All results (most recent first)</h3><table><tr><th>Header</th><th>Evaluated by</th><th>Method</th><th>Result</th><th>Details</th><th>Properties</th></tr>");
        for (an.auth) |r| {
            try o.appendSlice(a, "<tr><td>");
            try esc(a, &o, r.header);
            if (r.instance.len > 0) try o.print(a, " i={s}", .{r.instance});
            try o.appendSlice(a, "</td><td class=\"mono\">");
            try esc(a, &o, r.authserv);
            try o.appendSlice(a, "</td><td>");
            try esc(a, &o, r.method);
            try o.print(a, "</td><td class=\"{s}\">", .{resultClass(r.result)});
            try esc(a, &o, r.result);
            try o.appendSlice(a, "</td><td>");
            try esc(a, &o, r.detail);
            try o.appendSlice(a, "</td><td class=\"mono\">");
            try esc(a, &o, r.props);
            try o.appendSlice(a, "</td></tr>");
        }
        try o.appendSlice(a, "</table>");
    }
    if (an.signatures.len > 0) {
        try o.appendSlice(a, "<h3>DKIM and ARC signatures</h3><table><tr><th>Header</th><th>Domain (d=)</th><th>Selector (s=)</th><th>Algorithm</th><th>Signed at</th><th>ARC i / cv</th><th>Signed headers</th></tr>");
        for (an.signatures) |g| {
            try o.appendSlice(a, "<tr><td>");
            try esc(a, &o, g.header);
            try o.appendSlice(a, "</td><td>");
            try esc(a, &o, g.domain);
            try o.appendSlice(a, "</td><td>");
            try esc(a, &o, g.selector);
            try o.appendSlice(a, "</td><td>");
            try esc(a, &o, g.algorithm);
            try o.appendSlice(a, "</td><td>");
            try esc(a, &o, if (g.timestamp) |t| utc(&tb2, t) else "");
            try o.appendSlice(a, "</td><td>");
            if (std.ascii.startsWithIgnoreCase(g.header, "ARC-")) {
                try esc(a, &o, g.instance);
                if (g.chain.len > 0) {
                    try o.print(a, " / <span class=\"{s}\">", .{resultClass(g.chain)});
                    try esc(a, &o, g.chain);
                    try o.appendSlice(a, "</span>");
                }
            }
            try o.appendSlice(a, "</td><td class=\"mono\">");
            try esc(a, &o, g.signed_headers);
            try o.appendSlice(a, "</td></tr>");
        }
        try o.appendSlice(a, "</table>");
    }

    // ---- delivery path
    try o.appendSlice(a, "<h2>Delivery path</h2>");
    if (an.hops.len == 0) {
        try o.appendSlice(a, "<p class=\"muted\">No Received headers.</p>");
    } else {
        var max_delay: i64 = 1;
        for (an.hops) |h| if (h.delay) |d| {
            max_delay = @max(max_delay, d);
        };
        try o.appendSlice(a, "<table><tr><th>#</th><th>Delay</th><th></th><th>From (submitting host)</th><th>By (receiving host)</th><th>IP</th><th>With</th><th>TLS</th><th>Time</th></tr>");
        for (an.hops, 0..) |h, i| {
            var db: [32]u8 = undefined;
            try o.print(a, "<tr><td class=\"n\">{d}</td><td class=\"n{s}\">", .{ i + 1, if (h.delay != null and h.delay.? < 0) " neg" else "" });
            if (h.delay) |d| try esc(a, &o, hd.fmtDuration(&db, d)) else try o.appendSlice(a, "&nbsp;");
            try o.appendSlice(a, "</td><td style=\"width:120px\">");
            if (h.delay) |d| if (d > 0) try o.print(a, "<div class=\"bar\" style=\"width:{d}%\"></div>", .{@max(@divTrunc(d * 100, max_delay), 1)});
            try o.appendSlice(a, "</td><td class=\"mono\">");
            try esc(a, &o, h.from);
            if (h.from_detail.len > 0) {
                try o.appendSlice(a, "<br><span class=\"muted\">");
                try esc(a, &o, h.from_detail);
                try o.appendSlice(a, "</span>");
            }
            try o.appendSlice(a, "</td><td class=\"mono\">");
            try esc(a, &o, h.by);
            if (!std.ascii.eqlIgnoreCase(h.header, "Received")) try o.print(a, "<br><span class=\"muted\">({s})</span>", .{h.header});
            try o.appendSlice(a, "</td><td class=\"mono\">");
            try esc(a, &o, h.ip);
            if (h.ip.len > 0 and hd.isPrivateIp(h.ip)) try o.appendSlice(a, " <span class=\"muted\">(private)</span>");
            try o.appendSlice(a, "</td><td>");
            try esc(a, &o, h.with);
            try o.appendSlice(a, "</td><td>");
            try esc(a, &o, h.tls);
            try o.appendSlice(a, "</td><td style=\"white-space:nowrap\">");
            try esc(a, &o, fmt_time(&tb, h.time));
            try o.appendSlice(a, "</td></tr>");
        }
        try o.appendSlice(a, "</table><p class=\"note\">Origin first. Delays are the difference between the times each server recorded; a negative delay means the servers' clocks disagree.");
        if (an.transit) |t| {
            var db: [32]u8 = undefined;
            try o.print(a, " Total: {s}.", .{hd.fmtDuration(&db, t)});
        }
        try o.appendSlice(a, "</p>");
    }

    // ---- anti-spam
    if (an.fields.len > 0) {
        try o.appendSlice(a, "<h2>Anti-spam and filtering</h2>");
        var group: []const u8 = "";
        var open = false;
        for (an.fields) |f| {
            if (!std.mem.eql(u8, f.group, group)) {
                if (open) try o.appendSlice(a, "</table>");
                group = f.group;
                try o.appendSlice(a, "<h3>");
                try esc(a, &o, group);
                try o.appendSlice(a, "</h3><table><tr><th>Field</th><th>Value</th><th>Meaning</th></tr>");
                open = true;
            }
            try o.appendSlice(a, "<tr><td class=\"k\">");
            try esc(a, &o, f.key);
            try o.appendSlice(a, "</td><td class=\"mono\">");
            try esc(a, &o, f.value);
            try o.appendSlice(a, "</td><td>");
            try esc(a, &o, f.meaning);
            try o.appendSlice(a, "</td></tr>");
        }
        if (open) try o.appendSlice(a, "</table>");
    }

    // ---- indicators
    if (an.iocs.len > 0) {
        try o.appendSlice(a, "<h2>Indicators</h2><p class=\"note\">Collected from the headers for follow-up (block lists, reputation, message trace). Not looked up by pstview.</p><table><tr><th>Type</th><th>Value</th><th>Found in</th></tr>");
        inline for (.{ hd.IocKind.ip, hd.IocKind.host, hd.IocKind.email, hd.IocKind.url }) |kind| {
            for (an.iocs) |i| {
                if (i.kind != kind) continue;
                try o.print(a, "<tr><td>{s}</td><td class=\"mono\">", .{kind.label()});
                try esc(a, &o, i.value);
                if (i.private) try o.appendSlice(a, " <span class=\"muted\">(private)</span>");
                try o.appendSlice(a, "</td><td>");
                try esc(a, &o, i.source);
                try o.appendSlice(a, "</td></tr>");
            }
        }
        try o.appendSlice(a, "</table>");
    }

    // ---- all headers
    try o.print(a, "<h2>All headers ({d})</h2><p class=\"note\">In stored order: the top header was added last (closest to the recipient).</p><table><tr><th>#</th><th>Header</th><th>Value</th></tr>", .{an.all.len});
    for (an.all, 0..) |h, i| {
        try o.print(a, "<tr><td class=\"n\">{d}</td><td class=\"k\">", .{i + 1});
        try esc(a, &o, h.name);
        try o.appendSlice(a, "</td><td class=\"mono\">");
        try esc(a, &o, h.value);
        try o.appendSlice(a, "</td></tr>");
    }
    try o.appendSlice(a, "</table></body></html>");
    return o.toOwnedSlice(a);
}

fn card(a: Allocator, o: *List, title: []const u8, result: []const u8, domain: []const u8, al: hd.Alignment) !void {
    try o.print(a, "<div class=\"card\"><b>{s}</b><span class=\"{s}\">", .{ title, resultClass(result) });
    try esc(a, o, hd.orDash(result));
    try o.appendSlice(a, "</span><div class=\"note\">");
    try esc(a, o, if (domain.len > 0) domain else "no domain recorded");
    try o.print(a, " &middot; <span class=\"{s}\">{s}</span></div></div>", .{ switch (al) {
        .aligned => "ok",
        .not_aligned => "warn",
        .unknown => "muted",
    }, al.label() });
}

/// Plain-text version of the full report (for `pstx headers` / `pstx analyse`).
pub fn text(a: Allocator, an: hd.Analysis, fmt_time: TimeFmt) ![]u8 {
    var o: List = .empty;
    var tb: [96]u8 = undefined;
    var tb2: [64]u8 = undefined;
    try o.appendSlice(a, hd.reportText(a, an, fmt_time));
    if (!an.has_headers) return o.toOwnedSlice(a);
    try o.appendSlice(a, "\n== Summary\n");
    const pairs = [_][2][]const u8{
        .{ "Subject", an.subject },           .{ "Sender", an.sender },         .{ "To", an.to },                   .{ "Cc", an.cc },
        .{ "Delivered-To", an.delivered_to }, .{ "Message-ID", an.message_id }, .{ "In-Reply-To", an.in_reply_to },
    };
    for (pairs) |p| if (p[1].len > 0) try o.print(a, "  {s: <13} {s}\n", .{ p[0], p[1] });
    if (an.date) |d| try o.print(a, "  {s: <13} {s}  ({s})\n", .{ "Date", fmt_time(&tb, d), utc(&tb2, d) });
    try o.print(a, "  {s: <13} {s}\n", .{ "DMARC (ours)", an.dmarcComputed() });
    if (an.auth.len > 0) {
        try o.appendSlice(a, "\n== Authentication results (most recent first)\n");
        for (an.auth) |r| {
            try o.print(a, "  {s}{s}{s}{s}{s}: {s}={s}", .{ r.header, if (r.instance.len > 0) " i=" else "", r.instance, if (r.authserv.len > 0) " by " else "", r.authserv, r.method, r.result });
            if (r.detail.len > 0) try o.print(a, " ({s})", .{r.detail});
            if (r.props.len > 0) try o.print(a, " {s}", .{r.props});
            try o.append(a, '\n');
        }
    }
    if (an.signatures.len > 0) {
        try o.appendSlice(a, "\n== DKIM / ARC signatures\n");
        for (an.signatures) |g| {
            try o.print(a, "  {s}: d={s} s={s} a={s}", .{ g.header, g.domain, g.selector, g.algorithm });
            if (g.instance.len > 0 and std.ascii.startsWithIgnoreCase(g.header, "ARC-")) try o.print(a, " i={s}", .{g.instance});
            if (g.chain.len > 0) try o.print(a, " cv={s}", .{g.chain});
            if (g.timestamp) |t| try o.print(a, " signed {s}", .{utc(&tb2, t)});
            if (g.signed_headers.len > 0) try o.print(a, "\n      h={s}", .{g.signed_headers});
            try o.append(a, '\n');
        }
    }
    if (an.hops.len > 0) {
        try o.appendSlice(a, "\n== Received hops (origin first)\n");
        for (an.hops, 0..) |h, i| {
            var db: [32]u8 = undefined;
            try o.print(a, "  {d:>2}. {s: >12}  {s}\n", .{ i + 1, if (h.delay) |d| hd.fmtDuration(&db, d) else "", fmt_time(&tb, h.time) });
            try o.print(a, "      from {s}{s}{s}{s}\n      by   {s}{s}{s}{s}\n", .{ hd.orDash(h.from), if (h.from_detail.len > 0) " (" else "", h.from_detail, if (h.from_detail.len > 0) ")" else "", hd.orDash(h.by), if (h.with.len > 0) " with " else "", h.with, if (h.tls.len > 0) (std.fmt.allocPrint(a, " [{s}]", .{h.tls}) catch "") else "" });
        }
    }
    if (an.fields.len > 0) {
        try o.appendSlice(a, "\n== Anti-spam and filtering\n");
        var group: []const u8 = "";
        for (an.fields) |f| {
            if (!std.mem.eql(u8, f.group, group)) {
                group = f.group;
                try o.print(a, "  [{s}]\n", .{group});
            }
            try o.print(a, "    {s} = {s}{s}{s}\n", .{ f.key, f.value, if (f.meaning.len > 0) "   -- " else "", f.meaning });
        }
    }
    if (an.iocs.len > 0) {
        try o.appendSlice(a, "\n== Indicators (not looked up)\n");
        for (an.iocs) |i| try o.print(a, "  {s: <15} {s}{s}   ({s})\n", .{ i.kind.label(), i.value, if (i.private) " [private]" else "", i.source });
    }
    return o.toOwnedSlice(a);
}
