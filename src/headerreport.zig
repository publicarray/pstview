//! Message-header analysis reports: a standalone HTML page (in the style of Microsoft's Message
//! Header Analyzer / MXToolbox / Google Admin Toolbox) and an equivalent plain-text report.
//! Input is `headers.analyseDetailed`. Portable; no network access (the page blocks all loads).

const std = @import("std");
const Allocator = std.mem.Allocator;
const hd = @import("headers.zig");

pub const TimeFmt = *const fn (buf: []u8, t: ?i64) []const u8;

const List = std.ArrayList(u8);

fn esc(a: Allocator, out: *List, s: []const u8) !void {
    for (s) |c| switch (c) {
        '<' => try out.appendSlice(a, "&lt;"),
        '>' => try out.appendSlice(a, "&gt;"),
        '&' => try out.appendSlice(a, "&amp;"),
        '"' => try out.appendSlice(a, "&quot;"),
        else => try out.append(a, c),
    };
}

fn utc(buf: []u8, t: ?i64) []const u8 {
    const v = t orelse return "";
    const d = @import("pst.zig").unixToDateTime(v);
    return std.fmt.bufPrint(buf, "{d:0>4}-{d:0>2}-{d:0>2} {d:0>2}:{d:0>2}:{d:0>2} UTC", .{ d.year, d.month, d.day, d.hour, d.minute, d.second }) catch "";
}

fn resultClass(r: []const u8) []const u8 {
    if (std.ascii.startsWithIgnoreCase(r, "pass") or std.ascii.startsWithIgnoreCase(r, "bestguesspass")) return "ok";
    if (std.ascii.startsWithIgnoreCase(r, "fail") or std.ascii.startsWithIgnoreCase(r, "permerror") or std.ascii.startsWithIgnoreCase(r, "hardfail")) return "bad";
    if (std.ascii.startsWithIgnoreCase(r, "softfail") or std.ascii.startsWithIgnoreCase(r, "temperror") or std.ascii.startsWithIgnoreCase(r, "policy")) return "warn";
    return "muted";
}

fn sevClass(s: hd.Severity) []const u8 {
    return switch (s) {
        .high => "bad",
        .medium => "warn",
        .low => "low",
        .info, .none => "muted",
    };
}

